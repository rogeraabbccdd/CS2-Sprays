#!/usr/bin/env python3
"""Sync a folder of spray images into the workshop addon and the plugin config.

The spray menu cannot load images at runtime: the client's custom HUD validator only allows
basic Panel/Label/Button layouts, and panorama CSS only accepts file://, panel:// and s2r://
URLs. So every menu picture has to be compiled into the workshop addon, next to the spray
materials.

What it does, for every image in --images (upright, any size, transparency is kept):
  * writes the decal material into <addon>/materials/sprays/:
    <id>.png (square, turned 90 degrees counterclockwise), <id>_trans.png (translucency
    mask) and <id>.vmat
  * writes the 128x128 menu picture <addon>/panorama/images/custom_game/sprays/<id>.png
  * adds { "Name", "Material", "Image" } to "Sprays" in the plugin config (existing names and
    order are kept; sprays whose image is gone are only reported, never removed)
  * rewrites <addon>/panorama/styles/custom_game/sprays_images.css: one class per menu picture
  * copies sprays.xml and sprays.css into the addon when they are missing

<id> is the file name in lower case, with characters other than a-z, 0-9, _ and - replaced
by _. Existing sprays are skipped unless --force is given. With --compile the materials and the
stylesheet are compiled with CS2's resourcecompiler; then republish the addon.

Requires Pillow (pip install pillow).

Example:
  python tools/sync_sprays.py --images sprays --config CS2-Sprays.json \\
      --addon "C:/.../content/csgo_addons/my_addon"
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parents[1]
PREVIEW_SIZE = 128  # must match .spray-img in sprays.css
PREVIEW_DIR = "panorama/images/custom_game/sprays"
CSS_PATH = "panorama/styles/custom_game/sprays_images.css"
MENU_FILES = ["panorama/layout/custom_game/sprays.xml", "panorama/styles/custom_game/sprays.css"]
IMAGE_TYPES = {".png", ".jpg", ".jpeg", ".webp", ".bmp", ".tga"}

VMAT = """// THIS FILE IS AUTO-GENERATED

Layer0
{{
	shader "csgo_projected_decals.vfx"

	//---- Decal ----
	F_BLEND_MODE 1 // Mod2X

	//---- Alpha ----
	g_flDecalZAlphaScale "0.010"

	//---- Color ----
	TextureColor "{color}"

	//---- Translucent ----
	TextureTranslucency "{trans}"
}}
"""

CSS_HEADER = """/* Spray menu pictures, generated by tools/sync_sprays.py. One class per PNG in
   panorama/images/custom_game/sprays/; the plugin puts ".spray-i-<Image>" on each card.
   A file:// reference makes the resource compiler build the PNG with this stylesheet. */
"""


def spray_id(name):
    return re.sub(r"[^a-z0-9_-]", "_", name.lower())


def fit_square(image, size):
    """Scale the image to fit a size x size square, centered on a transparent background."""
    image = image.copy()
    image.thumbnail((size, size), Image.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(image, ((size - image.width) // 2, (size - image.height) // 2), image)
    return canvas


def write_spray(source, addon, folder, sid, size):
    image = Image.open(source).convert("RGBA")

    # env_decal shows the texture turned 90 degrees, so store it turned the other way
    # (CS2-Sprays places wall decals with pitch 90)
    square = fit_square(image, size).rotate(90)
    material_dir = addon / "materials" / folder
    material_dir.mkdir(parents=True, exist_ok=True)

    color = Image.new("RGB", square.size, (0, 0, 0))
    color.paste(square, mask=square)
    color.save(material_dir / f"{sid}.png")

    alpha = square.getchannel("A")
    Image.merge("RGB", (alpha, alpha, alpha)).save(material_dir / f"{sid}_trans.png")

    rel = f"materials/{folder}/{sid}"
    (material_dir / f"{sid}.vmat").write_text(VMAT.format(color=f"{rel}.png", trans=f"{rel}_trans.png"),
                                              encoding="utf-8", newline="\n")

    preview_dir = addon / PREVIEW_DIR
    preview_dir.mkdir(parents=True, exist_ok=True)
    fit_square(image, PREVIEW_SIZE).save(preview_dir / f"{sid}.png")


def build_css(preview_dir):
    ids = sorted(p.stem for p in preview_dir.glob("*.png")) if preview_dir.is_dir() else []
    out = [CSS_HEADER]
    for sid in ids:
        out.append(f'.spray-i-{spray_id(sid)} {{ background-image: url("file://{{images}}/custom_game/sprays/{sid}.png"); }}')
    return "\n".join(out) + "\n", len(ids)


def compile_files(addon, files):
    # <CS2>/content/csgo_addons/<addon> -> <CS2>/game/bin/win64/resourcecompiler.exe
    cs2_root = addon.resolve().parents[2]
    compiler = cs2_root / "game" / "bin" / "win64" / "resourcecompiler.exe"
    if not compiler.is_file():
        raise SystemExit(f"resourcecompiler not found at {compiler}; is the addon inside <CS2>/content/csgo_addons?")

    print("Compiling ...")
    failed = False
    for path in files:
        result = subprocess.run([str(compiler), "-nop4", "-i", str(path.resolve())],
                                cwd=compiler.parent, capture_output=True, text=True, errors="replace")
        summary = [line.strip() for line in result.stdout.splitlines() if "compiled," in line]
        print(f"  {path.relative_to(addon).as_posix()}: {summary[-1] if summary else '(no summary from resourcecompiler)'}")
        errors = [line.strip() for line in result.stdout.splitlines() if "error" in line.lower() and "compiled," not in line]
        for line in errors[:20]:
            print(f"    {line}")
        failed |= result.returncode != 0
    if failed:
        raise SystemExit("resourcecompiler reported errors")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--images", required=True, help="folder with the spray images (png, jpg, webp, ...)")
    ap.add_argument("--config", default="CS2-Sprays.json",
                    help="path to the plugin config (default: CS2-Sprays.json)")
    ap.add_argument("--addon", required=True, help="the workshop addon's content folder")
    ap.add_argument("--size", type=int, default=512, help="material texture size, a power of 2 (default: 512)")
    ap.add_argument("--folder", default="sprays", help="material folder under materials/ (default: sprays)")
    ap.add_argument("--prune", action="store_true", help="remove config sprays in materials/<folder>/ whose image is no longer in --images")
    ap.add_argument("--compile", action="store_true", help="compile the new materials and sprays_images.css with CS2's"
                                                     " resourcecompiler (needs the addon inside <CS2>/content/csgo_addons)")
    ap.add_argument("--force", action="store_true", help="regenerate sprays that already exist in the addon")
    ap.add_argument("--dry-run", action="store_true", help="show changes without writing anything")
    args = ap.parse_args()

    if not args.addon.strip():
        raise SystemExit("--addon is empty; pass the addon content folder.")
    addon = Path(args.addon)
    if not addon.is_dir():
        raise SystemExit(f"{addon} does not exist; pass the addon content folder.")
    source_dir = Path(args.images)
    if not source_dir.is_dir():
        raise SystemExit(f"{source_dir} is not a folder.")
    if args.size < 16 or args.size & (args.size - 1):
        raise SystemExit("--size must be a power of 2 (e.g. 256, 512, 1024).")

    # Images
    sources = {}
    for path in sorted(source_dir.iterdir()):
        if path.suffix.lower() not in IMAGE_TYPES:
            continue
        sid = spray_id(path.stem)
        if sid in sources:
            print(f"  ! {path.name} has the same id '{sid}' as {sources[sid].name}, skipped")
            continue
        sources[sid] = path
    print(f"Found {len(sources)} images in {source_dir.resolve()}")

    # Menu files
    copied = []
    for rel in MENU_FILES:
        if not (addon / rel).exists():
            print(f"  + {rel} (copied from the repo)")
            copied.append(addon / rel)
            if not args.dry_run:
                (addon / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(REPO / "addon" / rel, addon / rel)

    # Materials and menu pictures
    written = []
    failed = set()
    for sid, path in sources.items():
        exists = (addon / "materials" / args.folder / f"{sid}.vmat").exists() and (addon / PREVIEW_DIR / f"{sid}.png").exists()
        if exists and not args.force:
            continue
        written.append(sid)
        if args.dry_run:
            continue
        try:
            write_spray(path, addon, args.folder, sid, args.size)
        except Exception as ex:  # keep going; one bad image should not stop the sync
            written.remove(sid)
            failed.add(sid)
            print(f"  ! {path.name} failed: {ex}")
    print(f"Sprays: {len(written)} written, {len(failed)} failed -> {(addon / 'materials' / args.folder).resolve()}")

    # Config
    config_path = Path(args.config)
    raw = config_path.read_bytes().decode("utf-8-sig") if config_path.exists() else "{}"
    config = json.loads(raw)
    sprays = config.setdefault("Sprays", [])
    prefix = f"materials/{args.folder}/"
    listed = set()
    pruned = []
    kept = []
    for spray in sprays:
        sid = spray.get("Image", "")
        managed = str(spray.get("Material", "")).startswith(prefix)
        if managed and sid not in sources:
            if args.prune:
                pruned.append(spray)
                print(f"  - {spray.get('Name')} ({sid}) has no image any more, removed")
                continue
            print(f"  ? {spray.get('Name')} ({sid}) has no image in {source_dir.name} (use --prune to remove it)")
        listed.add(sid)
        kept.append(spray)

    added = []
    for sid, path in sources.items():
        if sid in listed or sid in failed:
            continue
        spray = {"Name": path.stem, "Material": f"{prefix}{sid}.vmat", "Image": sid}
        kept.append(spray)
        added.append(spray)
        print(f"  + {spray['Name']} -> {spray['Material']}")
    config["Sprays"] = kept
    print(f"{config_path.name}: {len(added)} added, {len(pruned)} removed")

    if args.dry_run:
        print("Dry run, nothing written.")
        return

    if added or pruned:
        if config_path.exists():
            shutil.copyfile(config_path, config_path.with_name(config_path.name + ".bak"))
        config_path.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")

    css, count = build_css(addon / PREVIEW_DIR)
    css_file = addon / CSS_PATH
    css_file.parent.mkdir(parents=True, exist_ok=True)
    css_file.write_text(css, encoding="utf-8", newline="\n")
    print(f"Wrote {count} menu pictures to {css_file.resolve()}")

    if args.compile:
        # Each file on its own: compiling the layout does not recompile a changed stylesheet
        compile_files(addon, copied + [addon / "materials" / args.folder / f"{sid}.vmat" for sid in written] + [css_file])


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(1)
